const mongoose = require("mongoose");
const Listing = require("../models/Listing");
const Bid = require("../models/Bid");
const ProxyBid = require("../models/ProxyBid");
const notificationService = require("./notificationService");
const socketService = require("./socketService");

// In-flight evaluation tracker to prevent concurrent or re-entrant evaluation on the same listing
const activeEvaluations = new Set();

/**
 * Normalizes an amount to 2 decimal places
 */
function normalizeAmount(val) {
  return Math.round(Number(val) * 100) / 100;
}

/**
 * Places a bid with atomic concurrency control and emits Socket.IO updates
 * @param {object} params
 * @param {string} params.listingId - Target listing ObjectId
 * @param {string} params.bidderId - User ObjectId of bidder
 * @param {number} params.amount - Numeric bid amount
 * @param {boolean} [params.isAutomatic=false] - True if generated by proxy engine
 * @returns {Promise<object>} { listing, bid, nextMinBid }
 */
async function placeBidCore({ listingId, bidderId, amount, isAutomatic = false }) {
  if (!listingId || !mongoose.Types.ObjectId.isValid(listingId)) {
    const error = new Error("A valid listing ID format is required.");
    error.statusCode = 400;
    throw error;
  }

  const normalizedAmount = normalizeAmount(amount);
  if (isNaN(normalizedAmount) || normalizedAmount <= 0) {
    const error = new Error("Bid amount must be a valid positive number greater than ₹0.00.");
    error.statusCode = 400;
    throw error;
  }

  // 1. Fetch listing
  const listing = await Listing.findById(listingId);
  if (!listing) {
    const error = new Error("Listing not found.");
    error.statusCode = 404;
    throw error;
  }

  // 2. Validate listing status and deadline
  if (listing.status !== "active") {
    const error = new Error(`Cannot bid on a ${listing.status} listing.`);
    error.statusCode = 400;
    throw error;
  }

  if (new Date(listing.auctionEndTime) <= new Date()) {
    const error = new Error("This auction has already ended. No new bids can be accepted.");
    error.statusCode = 400;
    throw error;
  }

  // 3. Prevent self-bidding against one's own listing
  if (listing.seller.toString() === bidderId.toString()) {
    const error = new Error("You cannot bid on your own listing.");
    error.statusCode = 403;
    throw error;
  }

  // 4. Calculate minimum required price
  const existingBidsCount = await Bid.countDocuments({ listing: listingId });
  const minIncrement = Number(listing.minBidIncrement) || 1.0;
  let minRequiredPrice = 0;

  if (existingBidsCount === 0) {
    minRequiredPrice = normalizeAmount(listing.startingPrice);
    if (normalizedAmount < minRequiredPrice) {
      const error = new Error(
        `First bid must be at least the starting price of ₹${minRequiredPrice.toFixed(2)}.`
      );
      error.statusCode = 400;
      throw error;
    }
  } else {
    minRequiredPrice = normalizeAmount(listing.currentPrice + minIncrement);
    if (normalizedAmount < minRequiredPrice) {
      const error = new Error(
        `Bid must be at least ₹${minRequiredPrice.toFixed(2)} (current bid ₹${listing.currentPrice.toFixed(2)} + min increment ₹${minIncrement.toFixed(2)}).`
      );
      error.statusCode = 400;
      throw error;
    }
  }

  // Find previous highest bid for outbid notifications
  const previousHighestBid = await Bid.findOne({ listing: listingId }).sort({
    amount: -1,
    createdAt: -1,
  });

  // Self-bidding check: prevent placing redundant automatic bids at or below current price
  if (
    previousHighestBid &&
    previousHighestBid.bidder.toString() === bidderId.toString() &&
    normalizedAmount <= listing.currentPrice &&
    isAutomatic
  ) {
    return {
      listing,
      bid: previousHighestBid,
      nextMinBid: normalizeAmount(listing.currentPrice + minIncrement),
      alreadyLeader: true,
    };
  }

  // 5. Atomic conditional update (Optimistic Concurrency Control)
  const updatedListing = await Listing.findOneAndUpdate(
    {
      _id: listingId,
      status: "active",
      auctionEndTime: { $gt: new Date() },
      currentPrice: listing.currentPrice, // Concurrency guard
    },
    {
      $set: { currentPrice: normalizedAmount },
    },
    {
      returnDocument: "after",
    }
  );

  if (!updatedListing) {
    const error = new Error(
      "A competing bid was placed just before yours. Please check the updated price and try again."
    );
    error.statusCode = 409;
    throw error;
  }

  // 6. Create Bid record
  const createdBid = await Bid.create({
    listing: listingId,
    bidder: bidderId,
    amount: normalizedAmount,
  });

  // Update proxy bid's lastBidAmount if this was an automatic bid
  if (isAutomatic) {
    await ProxyBid.updateOne(
      { listing: listingId, buyer: bidderId },
      { $set: { lastBidAmount: normalizedAmount } }
    );
  }

  // 7. Notifications
  try {
    // Notify seller of new bid
    await notificationService.createNotification({
      recipient: listing.seller,
      type: "NEW_BID",
      title: "New Bid Placed",
      message: `A new bid of ₹${normalizedAmount.toFixed(2)} was placed on "${listing.title}".`,
      listing: listing._id,
      bid: createdBid._id,
    });

    // Notify previous highest bidder of being outbid
    if (
      previousHighestBid &&
      previousHighestBid.bidder.toString() !== bidderId.toString()
    ) {
      await notificationService.createNotification({
        recipient: previousHighestBid.bidder,
        type: "OUTBID",
        title: "You Have Been Outbid",
        message: `You were outbid on "${listing.title}". The new highest bid is ₹${normalizedAmount.toFixed(2)}.`,
        listing: listing._id,
        bid: createdBid._id,
      });
    }

    // If automatic bid, notify the proxy bidder
    if (isAutomatic) {
      await notificationService.createNotification({
        recipient: bidderId,
        type: "PROXY_BID_PLACED",
        title: "Automatic Bid Placed",
        message: `Your automatic bid of ₹${normalizedAmount.toFixed(2)} was placed on "${listing.title}" to maintain your lead.`,
        listing: listing._id,
        bid: createdBid._id,
      });
    }
  } catch (notifErr) {
    console.error("Bid notification dispatch error:", notifErr.message);
  }

  // 8. Live Socket.IO Broadcast
  const totalBidsCount = await Bid.countDocuments({ listing: listingId });
  const nextMinBid = normalizeAmount(updatedListing.currentPrice + minIncrement);

  const populatedBid = await Bid.findById(createdBid._id).populate("bidder", "name");
  const publicBidEntry = {
    _id: populatedBid._id,
    amount: populatedBid.amount,
    createdAt: populatedBid.createdAt,
    bidder: {
      _id: populatedBid.bidder?._id || bidderId,
      id: populatedBid.bidder?._id || bidderId,
      name: populatedBid.bidder?.name || "Campus Buyer",
    },
  };

  try {
    socketService.broadcastBidUpdate(listingId, {
      listingId,
      currentPrice: updatedListing.currentPrice,
      nextMinBid,
      latestBid: publicBidEntry,
      status: updatedListing.status,
      auctionEndTime: updatedListing.auctionEndTime,
      totalBidsCount,
    });
  } catch (broadcastErr) {
    console.error("Live bid broadcast error:", broadcastErr.message);
  }

  return {
    listing: updatedListing,
    bid: publicBidEntry,
    nextMinBid,
  };
}

/**
 * Evaluates active proxy bids for a listing and places automatic counter-bids deterministically.
 * Prevents infinite loops, duplicate bids, and re-entrant proxy evaluation.
 * @param {string} listingId - Target listing ObjectId
 */
async function evaluateProxyBids(listingId) {
  const listingKey = listingId.toString();

  // Re-entrancy guard: if already evaluating proxies for this listing, do not overlap
  if (activeEvaluations.has(listingKey)) {
    return;
  }

  activeEvaluations.add(listingKey);

  try {
    const MAX_ROUNDS = 20; // Hard boundary to prevent any possibility of infinite loops
    let round = 0;

    while (round < MAX_ROUNDS) {
      round++;

      // 1. Fetch current listing state
      const listing = await Listing.findById(listingId);
      if (!listing || listing.status !== "active" || new Date(listing.auctionEndTime) <= new Date()) {
        break;
      }

      const minIncrement = Number(listing.minBidIncrement) || 1.0;
      const bidsCount = await Bid.countDocuments({ listing: listingId });
      const currentPrice = normalizeAmount(listing.currentPrice);

      const nextMinBid =
        bidsCount === 0
          ? normalizeAmount(listing.startingPrice)
          : normalizeAmount(currentPrice + minIncrement);

      // 2. Identify the current highest bidder
      const currentHighestBid = await Bid.findOne({ listing: listingId }).sort({
        amount: -1,
        createdAt: -1,
      });

      const currentLeaderId = currentHighestBid
        ? currentHighestBid.bidder.toString()
        : null;

      // 3. Find active proxies for this listing
      // Tie policy: higher maxAmount wins; on equal maxAmount, earlier createdAt wins
      const activeProxies = await ProxyBid.find({
        listing: listingId,
        isActive: true,
      }).sort({ maxAmount: -1, createdAt: 1 });

      if (!activeProxies || activeProxies.length === 0) {
        break;
      }

      // Check for proxies whose limit has been completely reached/exceeded by current price
      for (const p of activeProxies) {
        if (
          p.buyer.toString() !== currentLeaderId &&
          p.maxAmount < nextMinBid
        ) {
          try {
            await notificationService.createNotification({
              recipient: p.buyer,
              type: "PROXY_LIMIT_REACHED",
              title: "Automatic Bidding Limit Reached",
              message: `The current bid on "${listing.title}" (₹${currentPrice.toFixed(2)}) has reached or exceeded your automatic limit of ₹${p.maxAmount.toFixed(2)}.`,
              listing: listing._id,
              deduplicate: true,
            });
          } catch (notifErr) {
            // Silently continue
          }
        }
      }

      // 4. Filter eligible competing proxies (must NOT be current leader, and must afford nextMinBid)
      const eligibleProxies = activeProxies.filter(
        (p) => p.buyer.toString() !== currentLeaderId && p.maxAmount >= nextMinBid
      );

      if (eligibleProxies.length === 0) {
        // No competing proxy can bid. Auction is in equilibrium.
        break;
      }

      // Top eligible competing proxy
      const topCandidate = eligibleProxies[0];

      // Check if current leader also has an active proxy
      const leaderProxy = activeProxies.find(
        (p) => p.buyer.toString() === currentLeaderId
      );

      let bidToPlace = nextMinBid;

      if (!leaderProxy) {
        // Current leader is a manual bidder or has no active proxy:
        // Top candidate only needs to bid the minimum valid increment to take the lead
        bidToPlace = nextMinBid;
      } else {
        // Both candidate and current leader have active proxies competing
        const candidateMax = topCandidate.maxAmount;
        const leaderMax = leaderProxy.maxAmount;

        if (candidateMax === leaderMax) {
          // EQUAL MAX TIE POLICY:
          // The proxy activated earlier holds the priority at this maximum amount
          const candidateCreated = new Date(topCandidate.createdAt).getTime();
          const leaderCreated = new Date(leaderProxy.createdAt).getTime();

          if (leaderCreated <= candidateCreated) {
            // Leader was registered earlier: Leader has priority at this ceiling!
            // Leader defends up to candidateMax. Candidate cannot outbid.
            if (currentPrice < candidateMax) {
              await placeBidCore({
                listingId,
                bidderId: leaderProxy.buyer,
                amount: candidateMax,
                isAutomatic: true,
              });
            }
            break;
          } else {
            // Candidate was registered earlier: Candidate has priority at this ceiling!
            // Candidate takes the lead at candidateMax. Leader cannot outbid.
            await placeBidCore({
              listingId,
              bidderId: topCandidate.buyer,
              amount: candidateMax,
              isAutomatic: true,
            });
            break;
          }
        } else if (candidateMax > leaderMax) {
          // Candidate has higher ceiling than leader
          if (currentPrice < leaderMax) {
            // Leader defends up to leaderMax first
            try {
              await placeBidCore({
                listingId,
                bidderId: leaderProxy.buyer,
                amount: leaderMax,
                isAutomatic: true,
              });
            } catch (err) {
              // Ignore conflict or retry
            }
            continue;
          } else {
            // Current price is at leaderMax, candidate bids minimum increment to take lead
            bidToPlace = Math.min(candidateMax, normalizeAmount(leaderMax + minIncrement));
          }
        } else {
          // Leader has higher ceiling than candidate
          // Candidate bids up to candidateMax to contest
          bidToPlace = candidateMax;
        }
      }

      // Ensure bidToPlace never exceeds candidate's maxAmount
      if (bidToPlace > topCandidate.maxAmount) {
        bidToPlace = topCandidate.maxAmount;
      }

      // Double-check bidToPlace is at least nextMinBid
      if (bidToPlace < nextMinBid) {
        break;
      }

      // Place the automatic bid
      try {
        await placeBidCore({
          listingId,
          bidderId: topCandidate.buyer,
          amount: bidToPlace,
          isAutomatic: true,
        });
      } catch (placeErr) {
        // Break on conflict to allow outer flow to re-evaluate
        break;
      }
    }
  } catch (err) {
    console.error("evaluateProxyBids error:", err.message);
  } finally {
    activeEvaluations.delete(listingKey);
  }
}

module.exports = {
  placeBidCore,
  evaluateProxyBids,
  normalizeAmount,
};
